-- Lab-only sample data

CREATE TABLE DBA_LAB_DATABASES
(
    DB_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY
                  CONSTRAINT PK_DBA_LAB_DATABASES PRIMARY KEY,
    DATABASE_NAME VARCHAR2(30) NOT NULL,
    DATABASE_TYPE VARCHAR2(30) DEFAULT 'Oracle' NOT NULL,
    ENVIRONMENT   VARCHAR2(10) NOT NULL,
    VERSION       VARCHAR2(20) NOT NULL,
    HOST_NAME     VARCHAR2(50) NOT NULL,
    STATUS        VARCHAR2(20) NOT NULL,
    DR_ENABLED    VARCHAR2(3) DEFAULT 'NO' NOT NULL,
    REGION        VARCHAR2(50),
    OWNER_TEAM    VARCHAR2(50),
    LAST_CHECKED  DATE DEFAULT SYSDATE,
    NOTES         VARCHAR2(500),

    CONSTRAINT UK_DBA_LAB_DBNAME
        UNIQUE (DATABASE_NAME),

    CONSTRAINT CK_DBA_LAB_ENV
        CHECK (ENVIRONMENT IN ('PROD','UAT','DEV','TEST','DR')),

    CONSTRAINT CK_DBA_LAB_STATUS
        CHECK (STATUS IN ('ACTIVE','STANDBY','STOPPED','MAINTENANCE')),

    CONSTRAINT CK_DBA_LAB_DR
        CHECK (DR_ENABLED IN ('YES','NO'))
);

